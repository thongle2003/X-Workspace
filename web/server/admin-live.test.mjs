import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { createWorkflowStore } from './workflow-store.mjs';
import { createAPI } from './api.mjs';
import { buildLiveAdminSnapshot } from './admin-live.mjs';
import { SAMPLE_CSV } from '../domain.js';

test('admin live view follows Startup case, workspace, connection, and verified receipts',async t=>{
  const store=createWorkflowStore();
  const profile={name:'Startup kết nối thật',industry:'SaaS',stage:'Seed',location:'TP.HCM',summary:'Hồ sơ thử kết nối trực tiếp với trang quản trị.',target:1000};
  const project=store.act('founder',{type:'create-workspace',name:'Gọi vốn Seed',goal:'Chuẩn bị vòng gọi vốn mới',profile}).workspaces[0];
  store.act('founder',{type:'upload-financial',workspaceId:project.id,name:'private.csv',csv:SAMPLE_CSV});
  const created=store.act('founder',{type:'create-case',workspaceId:project.id,title:'Case gọi vốn trực tiếp',summary:'Startup gửi case để admin theo dõi trạng thái.'}).cases[0];
  store.act('founder',{type:'submit-case',caseId:created.id});
  store.act('founder',{type:'publish',workspaceId:project.id});
  const asked=store.act('investor',{type:'request-access',workspaceId:project.id,message:'Tôi muốn tìm hiểu hồ sơ và trao đổi với Startup.'});
  const requestId=asked.requests[0].id;
  store.act('founder',{type:'decide-access',requestId,decision:'approved'});
  store.settleConnectionPayment({requestId,party:'startup',providerPaymentId:'verified-startup-1',amountVnd:250_000,currency:'VND'});
  const first=buildLiveAdminSnapshot(store.exportData());
  assert.deepEqual(first.accounts.map(item=>item.id),['founder','investor']);
  assert.equal(first.workspaces.find(item=>item.id===project.id).published,true);
  assert.equal(first.cases.find(item=>item.id===created.id).status,'awaiting_payment');
  assert.equal(first.connections.find(item=>item.id===requestId).status,'awaiting_payment');
  assert.equal(first.transactions.filter(item=>item.status==='paid').reduce((sum,item)=>sum+item.amount,0),250_000);
  assert.equal(first.transactions.filter(item=>item.status==='pending').length,2);
  assert.equal(JSON.stringify(first).includes('private.csv'),false);
  assert.equal(JSON.stringify(first).includes(SAMPLE_CSV.slice(0,30)),false);
  const catalog={...store.exportData(),workspaces:[...store.exportData().workspaces,{...project,id:'catalog-example',catalogListing:true}]};
  assert.equal(buildLiveAdminSnapshot(catalog).workspaces.some(item=>item.id==='catalog-example'),true);

  const server=http.createServer(createAPI({store,adminPassword:'test-admin-secret'}));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const base=`http://127.0.0.1:${server.address().port}`;
  assert.equal((await fetch(base+'/api/admin/dashboard')).status,401);
  const login=await fetch(base+'/api/admin/session',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:'test-admin-secret'})});
  const token=(await login.json()).sessionToken;
  const read=async()=>{const response=await fetch(base+'/api/admin/dashboard',{headers:{'x-admin-session':token}});assert.equal(response.status,200);return response.json();};
  assert.equal((await fetch(base+'/api/admin/dashboard',{method:'PATCH',headers:{'content-type':'application/json','x-admin-session':token},body:'{}'})).status,405);
  assert.equal((await read()).transactions.filter(item=>item.status==='paid').length,1);
  store.settleConnectionPayment({requestId,party:'investor',providerPaymentId:'verified-investor-1',amountVnd:250_000,currency:'VND'});
  const position=store.act('investor',{type:'record-investment',workspaceId:project.id,invested:120,ownership:4,date:'2026-11-15'}).portfolio[0];
  const second=await read();
  assert.equal(second.transactions.filter(item=>item.status==='paid').reduce((sum,item)=>sum+item.amount,0),500_000);
  assert.equal(second.connections.find(item=>item.id===requestId).status,'connected');
  assert.equal(second.transactions.find(item=>item.id===`listing-${created.id}`).status,'pending');
  assert.equal(second.investments.find(item=>item.id===position.id).investedMillionVnd,120);
  assert.throws(()=>store.adminWorkspace({workspaceId:project.id,operation:'delete',expectedRevision:second.revision}),{code:'WORKSPACE_IN_USE'});
  const caseURL=base+`/api/admin/cases/${encodeURIComponent(created.id)}`;
  const change=async(method,body,session=token)=>fetch(caseURL,{method,headers:{'content-type':'application/json','x-admin-session':session},body:JSON.stringify(body)});
  assert.equal((await change('PATCH',{flagged:true,expectedRevision:second.revision},'wrong-token')).status,401);
  const flaggedResponse=await change('PATCH',{flagged:true,expectedRevision:second.revision});
  assert.equal(flaggedResponse.status,200);
  const flagged=await flaggedResponse.json();
  assert.equal(flagged.cases.find(item=>item.id===created.id).flagged,true);
  assert.equal(store.snapshot('founder').cases.find(item=>item.id===created.id).flagged,true);
  assert.equal(createWorkflowStore({initialData:store.exportData()}).snapshot('founder').cases.find(item=>item.id===created.id).flagged,true);
  assert.equal((await change('DELETE',{expectedRevision:second.revision})).status,409);
  const unflaggedResponse=await change('PATCH',{flagged:false,expectedRevision:flagged.revision});
  assert.equal(unflaggedResponse.status,200);
  const unflagged=await unflaggedResponse.json();
  assert.equal(unflagged.cases.find(item=>item.id===created.id).flagged,false);
  const deletedResponse=await change('DELETE',{expectedRevision:unflagged.revision});
  assert.equal(deletedResponse.status,200);
  const deleted=await deletedResponse.json();
  assert.equal(deleted.cases.some(item=>item.id===created.id),false);
  assert.equal(deleted.transactions.some(item=>item.caseId===created.id),false);
  assert.equal(store.snapshot('founder').cases.some(item=>item.id===created.id),false);
  assert.equal(deleted.workspaces.some(item=>item.id===project.id),true);
  assert.equal(deleted.connections.some(item=>item.id===requestId),true);
});

test('admin projects match Startup Marketplace and deleted listings stay deleted after restart',()=>{
  const store=createWorkflowStore({seedMarketplace:true});
  const before=store.snapshot('investor').marketplace;
  assert.equal(before.length,10);
  const first=buildLiveAdminSnapshot(store.exportData());
  assert.deepEqual(first.workspaces.map(item=>item.name),before.map(item=>item.profile.name));
  const selected=before[0];
  store.adminWorkspace({workspaceId:selected.id,operation:'flag',expectedRevision:first.revision});
  const flagged=buildLiveAdminSnapshot(store.exportData());
  assert.equal(flagged.workspaces.find(item=>item.id===selected.id).flagged,true);
  assert.equal(store.snapshot('investor').marketplace.some(item=>item.id===selected.id),true);
  store.adminWorkspace({workspaceId:selected.id,operation:'delete',expectedRevision:flagged.revision});
  assert.equal(store.snapshot('investor').marketplace.some(item=>item.id===selected.id),false);
  const restarted=createWorkflowStore({initialData:store.exportData(),seedMarketplace:true});
  assert.equal(restarted.snapshot('investor').marketplace.length,9);
  assert.equal(buildLiveAdminSnapshot(restarted.exportData()).workspaces.length,9);
});

test('admin can suspend and restore Startup and Investor accounts and change plan',async t=>{
  const store=createWorkflowStore();
  const server=http.createServer(createAPI({store,adminPassword:'account-admin-secret'}));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const base=`http://127.0.0.1:${server.address().port}`;
  const session=async role=>fetch(base+'/api/demo/session',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({role})});
  const investor=await (await session('investor')).json();
  const startup=await (await session('founder')).json();
  const login=await fetch(base+'/api/admin/session',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:'account-admin-secret'})});
  const adminToken=(await login.json()).sessionToken;
  const dashboard=async()=>{const response=await fetch(base+'/api/admin/dashboard',{headers:{'x-admin-session':adminToken}});return response.json();};
  const change=(id,body,token=adminToken)=>fetch(base+`/api/admin/accounts/${id}`,{method:'PATCH',headers:{'content-type':'application/json','x-admin-session':token},body:JSON.stringify(body)});
  const userStatus=async token=>fetch(base+'/api/workflow',{headers:{'x-demo-session':token}});
  const initial=await dashboard();
  assert.equal((await change('investor',{status:'suspended',expectedRevision:initial.revision},'bad-token')).status,401);
  assert.equal((await change('investor',{status:'suspended',expectedRevision:initial.revision})).status,200);
  assert.equal((await userStatus(investor.sessionToken)).status,403);
  assert.equal((await session('investor')).status,403);
  assert.equal((await userStatus(startup.sessionToken)).status,200);
  const afterSuspend=await dashboard();
  assert.equal(afterSuspend.accounts.find(item=>item.id==='investor').status,'suspended');
  assert.equal((await change('investor',{status:'active',expectedRevision:initial.revision})).status,409);
  assert.equal((await change('investor',{status:'active',expectedRevision:afterSuspend.revision})).status,200);
  assert.equal((await userStatus(investor.sessionToken)).status,200);
  const afterRestore=await dashboard();
  assert.equal((await change('founder',{tier:'plus',billing:'annual',expectedRevision:afterRestore.revision})).status,200);
  const founderSnapshot=await (await userStatus(startup.sessionToken)).json();
  assert.equal(founderSnapshot.plan.tier,'plus');
  assert.equal(founderSnapshot.plan.billing,'annual');
  const afterPlan=await dashboard();
  assert.equal(afterPlan.accounts.find(item=>item.id==='founder').tier,'plus');
  assert.equal(createWorkflowStore({initialData:store.exportData()}).exportData().accounts.founder.billing,'annual');
  const profileResponse=await change('founder',{name:'Startup quản lý',email:'startup@example.com',permissions:{workspaces:false,aiAnalysis:false},expectedRevision:afterPlan.revision});
  assert.equal(profileResponse.status,200);
  const profile=await profileResponse.json();
  assert.equal(profile.accounts.find(item=>item.id==='founder').name,'Startup quản lý');
  assert.equal(store.snapshot('founder').user.name,'Startup quản lý');
  assert.equal(store.snapshot('founder').permissions.workspaces,false);
  assert.throws(()=>store.act('founder',{type:'create-workspace',name:'Blocked',goal:'Blocked by admin'}),{code:'ACCOUNT_PERMISSION'});
  const blockedAction=await fetch(base+'/api/workflow/actions',{method:'POST',headers:{'content-type':'application/json','x-demo-session':startup.sessionToken},body:JSON.stringify({type:'create-workspace',name:'Blocked',goal:'Blocked by admin'})});
  assert.equal(blockedAction.status,403);
  assert.equal((await blockedAction.json()).code,'ACCOUNT_PERMISSION');
  assert.throws(()=>store.beginAnalysis('founder',{}),{code:'ACCOUNT_PERMISSION'});
  assert.equal(createWorkflowStore({initialData:store.exportData()}).snapshot('founder').permissions.aiAnalysis,false);
  const afterProfile=await dashboard();
  assert.equal((await change('investor',{permissions:{aiChat:false},expectedRevision:afterProfile.revision})).status,200);
  assert.throws(()=>store.beginChat('investor',{inputTokensEstimate:100}),{code:'ACCOUNT_PERMISSION'});
});
